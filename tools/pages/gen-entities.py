#!/usr/bin/env python3
# Regenerates lib/pages/entities.js (v1.395.0 Pages): the HTML 4.01 named
# character references + apos + the uppercase legacy aliases, and the HTML5
# list of names accepted without a trailing semicolon. Run from the repo root:
#   python3 tools/pages/gen-entities.py > lib/pages/entities.js
from html.entities import name2codepoint, html5

names = dict(name2codepoint)
names['apos'] = 39
for alias, cp in (('AMP', 38), ('COPY', 169), ('GT', 62), ('LT', 60), ('QUOT', 34), ('REG', 174)):
    names[alias] = cp
legacy = sorted(k for k in html5 if not k.endswith(';'))
assert all(k in names for k in legacy), [k for k in legacy if k not in names]

items = sorted(names.items())
rows = ['  ' + ', '.join(f'{k}:{v}' for k, v in items[i:i + 8]) + ',' for i in range(0, len(items), 8)]
leg = ['  ' + ', '.join("'" + x + "'" for x in legacy[i:i + 10]) + ',' for i in range(0, len(legacy), 10)]
print("""'use strict';

// lib/pages/entities.js - the named character references the Pages tidier
// decodes (lib/pages/tidy.js). GENERATED by tools/pages/gen-entities.py, never
// hand-edited: the HTML 4.01 set (Python's html.entities.name2codepoint) plus
// `apos` and the uppercase legacy aliases, as code points. LEGACY is the HTML5
// list of names a browser also accepts WITHOUT the trailing semicolon. A name
// not here is left as literal text, never guessed.

const NAMED = Object.freeze(Object.assign(Object.create(null), {""")
print('\n'.join(rows))
print("""}));

const LEGACY = new Set([""")
print('\n'.join(leg))
print("""]);

module.exports = { NAMED, LEGACY };""")
